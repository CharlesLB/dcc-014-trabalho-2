def _t(linhas: str) -> dict:
    """'base: m±d m±d ...' (ordem de METODOS) -> {base: {metodo: (m, d)}}."""
    out = {}
    for ln in linhas.strip().splitlines():
        b, vals = ln.split(":")
        pares = [v.split("±") for v in vals.split()]
        out[b.strip()] = {mt: (float(m), float(d)) for mt, (m, d) in zip(METODOS, pares)}
    return out


